void WDT_Init(WDT_TypeDef * WDTx, uint32_t peroid, uint32_t mode)
{
	SYS->CLKEN |= (0x01 << SYS_CLKEN_WDT_Pos);
	
	WDT_Stop(WDTx);		//����ǰ�ȹر�
	
	WDT_INTClr(WDTx);
	
	if(mode == WDT_MODE_RESET)
	{
		WDTx->LOAD = peroid/2;	// ��λģʽ���������趨ֵ������
		
		WDTx->CR |= (1 << WDT_CR_RSTEN_Pos);
	}
	else // mode == WDT_MODE_INTERRUPT
	{
		WDTx->LOAD = peroid;
		
		WDTx->CR &= ~(1 << WDT_CR_RSTEN_Pos);
	}
}

